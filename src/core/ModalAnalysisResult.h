#pragma once

#include "core/PhaseMap.h"

namespace digitqt::core {

/**
 * @brief Какие термы включать в подгонку S5 -- пользовательский выбор
 * (см. ParametersDock), как список "Выделенные аберрации" в референсном
 * инструменте. Пистон не выбираем отдельно -- это произвольное смещение
 * без физического смысла, убирается всегда.
 *
 * Термы, которые НЕ выбраны, просто не участвуют в МНК вообще (не
 * добавляются как колонка матрицы) -- значит, они остаются в остатке
 * нетронутыми, а не "вычитаются нулём".
 */
struct ModalTermSelection {
  bool tilt = true;
  bool defocus = true;
  bool astigmatism = true;
  bool coma = true;
  bool trefoil = true;
  bool spherical = true;
};

/**
 * @brief Коэффициенты низкочастотной раскладки волнового фронта.
 *
 * Базис -- простые полиномы от нормализованных пупильных координат x, y
 * в [-1, 1] (ведущий моном каждого термина ниже), но перед подгонкой
 * (см. ModalAnalysisStage) они численно ортогонализуются методом
 * Грама-Шмидта ПРЯМО по фактическим точкам апертуры измерения:
 *   1                       -- пистон
 *   x, y                    -- наклон X/Y
 *   x²+y²                   -- дефокус
 *   x²-y², xy               -- астигматизм (0°/45° составляющие)
 *   x³+xy², y³+x²y          -- кома (X/Y составляющие)
 *   x³-3xy², 3x²y-y³        -- трилистник (X/Y составляющие)
 *   (x²+y²)²                -- сферическая аберрация 3-го порядка
 *
 * Обычные (не ортогонализованные) мономы этого вида коррелируют друг с
 * другом внутри одной "радиальной семьи" -- пистон/дефокус/сферическая
 * все зависят только от r², а наклон/кома оба линейны по x (или по y)
 * вдоль своей оси. Без ортогонализации МНК даёт корректный суммарный
 * остаток, но включение/выключение одного термина (см.
 * ModalTermSelection, чекбоксы в ParametersDock) "перетекает" в
 * коэффициенты соседних термов той же семьи. Ортогонализация устраняет
 * это: каждый коэффициент -- независимая проекция на свой базисный
 * вектор, не зависящая от того, какие ещё термины сейчас выбраны.
 *
 * Аналитические формулы полиномов Цернике для этого не подходят --
 * они доказанно ортогональны только на идеальном круге, а апертура
 * здесь произвольной формы (возможны препятствия/вырезы), так что
 * ортогонализацию по факту делаем численно, на тех же точках, что и
 * сама подгонка.
 *
 * Значения — в тех же единицах, что и исходная карта (нанометры для
 * Measurement::wavefrontMap()).
 *
 * По мотивам классической раскладки аберраций в оригинальном проекте
 * Digit (InterfSolver/Tools/ClassicAberr.h: SPH_COEFF = пистон+наклон+
 * дефокус, AST_COEFF = астигматизм, COM_COEFF = кома), через обычный
 * МНК на Eigen, без переноса их собственных Matrix/Vector классов.
 */
struct ModalCoefficients {
  double piston = 0.0;
  double tiltX = 0.0;
  double tiltY = 0.0;
  double defocus = 0.0;
  double astigX = 0.0;     // x²-y² составляющая
  double astigY = 0.0;     // xy составляющая
  double comaX = 0.0;      // x³+xy² составляющая
  double comaY = 0.0;      // y³+x²y составляющая
  double trefoilX = 0.0;   // x³-3xy² составляющая
  double trefoilY = 0.0;   // 3x²y-y³ составляющая
  double spherical = 0.0;  // (x²+y²)² составляющая
};

/// Результат S5: коэффициенты + остаток (карта минус подогнанный полином)
/// -- это и есть "настоящие" особенности формы поверхности, без вклада
/// геометрии измерения (наклон/дефокус/астигматизм).
struct ModalAnalysisResult {
  ModalCoefficients coefficients;
  ModalTermSelection selection;  // какие термы реально подгонялись
  PhaseMap residual;
  double rmsBefore = 0.0;
  double rmsAfter = 0.0;

  bool isEmpty() const { return residual.isEmpty(); }

  void clear() {
    coefficients = ModalCoefficients();
    selection = ModalTermSelection();
    residual.clear();
    rmsBefore = 0.0;
    rmsAfter = 0.0;
  }
};

}  // namespace digitqt::core
