#pragma once

#include "core/PhaseMap.h"

namespace digitqt::core {

/**
 * @brief Какие термы включать в подгонку S5 -- пользовательский выбор
 * (см. ParametersDock), как список "Выделенные аберрации" в референсном
 * инструменте. Пистон не выбираем отдельно -- это произвольное смещение
 * без физического смысла, убирается всегда.
 *
 * Термы, которые НЕ выбраны, просто не участвуют в МНК вообще (не
 * добавляются как колонка матрицы) -- значит, они остаются в остатке
 * нетронутыми, а не "вычитаются нулём".
 */
struct ModalTermSelection {
  bool tilt = true;
  bool defocus = true;
  bool astigmatism = true;
  bool coma = true;
  bool trefoil = true;
  bool spherical = true;
};

/**
 * @brief Коэффициенты низкочастотной раскладки волнового фронта.
 *
 * Базис -- прямая транскрипция полиномов референсного инструмента
 * (DAPPSIM, Includes/Fitting.cpp, метод Seregin), не "учебниковые"
 * нормированные полиномы Цернике; координата y здесь -- нормализованная
 * пупильная координата в [-1, 1], растущая вниз по строкам изображения
 * (там, где у Seregin ось Y перевёрнута, знак учтён прямо в формуле):
 *   1                            -- пистон
 *   x, -y                        -- наклон X/Y
 *   x²+y²                        -- дефокус
 *   1.5(x²-y²), -xy              -- астигматизм (см. ниже про 3 терма Seregin)
 *   x³+xy²-(2/3)x                -- кома X
 *   (2/3)y-y³-x²y                -- кома Y
 *   3xy²-x³, 3x²y-y³             -- трилистник (X/Y составляющие)
 *   (x²+y²)²                     -- сферическая аберрация 3-го порядка
 *
 * Астигматизм у Seregin -- на самом деле 3 коэффициента ((3X²-1)/2, XY,
 * (3Y²-1)/2), первый и третий не ортогональны дефокусу. astigX здесь --
 * эквивалент их разности (1.5(x²-y²) = ((3X²-1)/2 - (3Y²-1)/2)), т.е.
 * "чистый" астигматизм без дефокусной примеси; astigY -- их крест-терм
 * (XY) как есть, с тем же переворотом Y.
 *
 * См. ModalAnalysisStage.cpp (buildTermHierarchy) для подробного разбора
 * соответствия каждого терма коду DAPPSIM.
 *
 * Термы (не считая пистона) коррелируют друг с другом внутри одной
 * "радиальной семьи" -- пистон/дефокус/сферическая все зависят только от
 * r², а наклон/кома оба линейны по x (или по y) вдоль своей оси. Способ
 * AnalyticZernike решает совместный МНК по всем выбранным термам сразу
 * (корректный суммарный остаток при любом подмножестве термов, но не
 * гарантирует, что включение/выключение одного термина не повлияет на
 * коэффициенты остальных); способ GramSchmidtOnAperture дополнительно
 * ортогонализует тот же базис численно, ПРЯМО по фактическим точкам
 * апертуры измерения -- тогда каждый коэффициент независим от того, какие
 * ещё термины сейчас выбраны, но численно уже не совпадает с DAPPSIM (см.
 * ModalTermSelection, чекбоксы в ParametersDock).
 *
 * Значения — в тех же единицах, что и исходная карта (нанометры для
 * Measurement::wavefrontMap()).
 */
struct ModalCoefficients {
  double piston = 0.0;
  double tiltX = 0.0;
  double tiltY = 0.0;
  double defocus = 0.0;
  double astigX = 0.0;     // 1.5(x²-y²) составляющая -- эквивалент разности термов Seregin
  double astigY = 0.0;     // -xy составляющая (крест-терм Seregin, с перевёрнутой Y)
  double comaX = 0.0;      // x³+xy²-(2/3)x составляющая (Seregin)
  double comaY = 0.0;      // (2/3)y-y³-x²y составляющая (Seregin, с перевёрнутой Y)
  double trefoilX = 0.0;   // 3xy²-x³ составляющая (Seregin)
  double trefoilY = 0.0;   // 3x²y-y³ составляющая (Seregin)
  double spherical = 0.0;  // (x²+y²)² составляющая (Seregin)
};

/// Результат S5: коэффициенты + остаток (карта минус подогнанный полином)
/// -- это и есть "настоящие" особенности формы поверхности, без вклада
/// геометрии измерения (наклон/дефокус/астигматизм).
struct ModalAnalysisResult {
  ModalCoefficients coefficients;
  ModalTermSelection selection;  // какие термы реально подгонялись
  PhaseMap residual;
  double rmsBefore = 0.0;
  double rmsAfter = 0.0;

  bool isEmpty() const { return residual.isEmpty(); }

  void clear() {
    coefficients = ModalCoefficients();
    selection = ModalTermSelection();
    residual.clear();
    rmsBefore = 0.0;
    rmsAfter = 0.0;
  }
};

}  // namespace digitqt::core
