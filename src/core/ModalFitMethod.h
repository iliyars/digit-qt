#pragma once

namespace digitqt::core {

enum class ModalFitMethod {
  /// Обычный совместный МНК по фиксированному базису (какой базис --
  /// отдельный выбор, см. PolynomialBasis) без численной ортогонализации
  /// -- термы одной "радиальной семьи" (пистон/дефокус/сферическая;
  /// наклон/кома) могут "делить" вклад между собой в зависимости от
  /// того, какое подмножество термов выбрано. Не зависит от формы
  /// апертуры, только от самого базиса -- при базисе Seregin даёт
  /// коэффициенты в тех же единицах, что и референсный инструмент
  /// DAPPSIM (см. ModalCoefficients / ModalAnalysisStage buildTermHierarchy).
  JointLeastSquares,

  /// Численная ортогонализация Грама-Шмидта прямо по фактическим
  /// точкам апертуры этого конкретного снимка. Работает для апертуры
  /// любой формы (не обязательно круг, может быть с вырезами), и
  /// включение/выключение одного чекбокса гарантированно не меняет
  /// коэффициент другого -- но результат привязан именно к этой
  /// апертуре и не совпадёт напрямую с другими программами.
  GramSchmidtOnAperture,

  /// Точная последовательная схема подгонки самого DAPPSIM (не
  /// совместный МНК по фиксированному базису, а прямая транскрипция
  /// Includes/Fitting.cpp: 7 стадий, каждая вычитает накопленную сумму
  /// ПРЕДЫДУЩИХ термов перед своим отдельным МНК). Термы одной
  /// "радиальной семьи" (ρ²/ρ⁴/ρ⁶/ρ⁸) появляются повторно на нескольких
  /// стадиях -- это не ошибка, так работает сам референсный алгоритм.
  /// См. SequentialSereginResult.h про то, какие из полученных чисел
  /// подтверждены побайтово против report.txt (piston/tiltX/tiltY/
  /// defocus), а какие -- честная транскрипция алгоритма, но не
  /// подтверждены против конкретных меток B0-B8/C/FIC того же отчёта
  /// (report.txt формирует WinFringe, чьих исходников нет).
  SequentialSeregin,
};

}
