#pragma once

#include "core/PhaseMap.h"

#include <string>

namespace digitqt::core {

struct UnwrapResult {
  /// Развёрнутая фаза в порядках полосы (радианы / 2*pi) -- в тех же
  /// единицах, что и PhaseMap остального конвейера. NaN там же, где NaN во
  /// входной карте.
  PhaseMap orders;
  /// Сколько несвязных областей пришлось разворачивать по отдельности.
  /// Больше 1 -- между областями неизвестна целая разность порядков, каждая
  /// развёрнута от своей точки отсчёта.
  int regionCount = 0;
  /// Точек в областях меньше minRegionSize -- они оставлены NaN и в
  /// regionCount не входят.
  int droppedPoints = 0;
};

/**
 * @brief Развёртка свёрнутой фазы, управляемая качеством (quality-guided
 * flood fill).
 *
 * Свёрнутая фаза известна только по модулю 2*pi. Развёртка восстанавливает
 * недостающие целые 2*pi, переходя от пикселя к соседу: новый пиксель
 * получает то значение из ряда w + 2*pi*k, которое ближе всего к уже
 * развёрнутому соседу. Ошибка в одном таком переходе (шум, разрыв полосы)
 * переносится на всё, что развёрнуто после него, поэтому порядок обхода --
 * от самых надёжных точек к самым ненадёжным: на каждом шаге берётся
 * переход с наибольшим качеством (минимум качества двух его концов), и
 * плохие точки разворачиваются последними, не успев испортить остальное.
 *
 * @param wrapped Свёрнутая фаза в радианах; NaN -- точка не участвует.
 * @param quality Надёжность каждой точки, больше -- лучше (для PSI --
 *        модуляция). Пустая карта -- все точки равноценны.
 * @param minRegionSize Связные области меньше этого числа точек
 *        выбрасываются: одиночные шумовые пиксели у края апертуры иначе
 *        считались бы отдельными "областями" с неизвестным порядком.
 */
bool unwrapPhase(const PhaseMap &wrapped, const PhaseMap &quality, UnwrapResult &out,
                 std::string &error, int minRegionSize = 1);

}  // namespace digitqt::core
